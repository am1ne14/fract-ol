#include "ft_printf.h"

int	ft_strchr(int c)
{
	int		i;
	char	*str;

	i = 0;
	str = "cspdiuxX%";
	while (str[i])
	{
		if (str[i] == (char)c)
			return (1);
		i++;
	}
	return (0);
}
